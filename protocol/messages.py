def get_message_category(name: str) -> str | None:
    """Return the category for a message name, or None if unknown.

    Accepts either a short name (e.g. "AccessoryPreviewErrorEvent") or a
    fully-qualified name (e.g. "Com.Ankama.Dofus.Server.Game.Protocol.AccessoryPreviewErrorEvent").
    """
    # If fully-qualified, extract the short name
    if "." in name:
        name = name.rsplit(".", 1)[-1]
    return ALL_MESSAGES.get(name)
